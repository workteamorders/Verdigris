// Writes the site's typed ABI from a compile output folder (forge `out/` or the solc-js check folder).
// Usage: node scripts/export-abi.mjs <dir with VerdigrisDisc.json> <outFile> <sourceLabel>
import fs from 'node:fs';
const [dir, outFile, label] = process.argv.slice(2);
const find = (n) => {
  for (const p of [`${dir}/${n}.json`, `${dir}/${n}.sol/${n}.json`]) if (fs.existsSync(p)) return JSON.parse(fs.readFileSync(p, 'utf8'));
  throw new Error(`no artifact for ${n} in ${dir}`);
};
const keep = (abi) => abi.filter((x) => x.type !== 'constructor');
const disc = keep(find('VerdigrisDisc').abi), rend = keep(find('VerdigrisRenderer').abi);
fs.writeFileSync(outFile, `// GENERATED by contracts/scripts/export-abi.mjs. Do not edit.\n// Source: ${label}\nexport const ABI_SOURCE = ${JSON.stringify(label)} as const;\nexport const discAbi = ${JSON.stringify(disc, null, 2)} as const;\nexport const rendererAbi = ${JSON.stringify(rend, null, 2)} as const;\n`);
console.log(`wrote ${outFile} (${disc.length} Disc entries, ${rend.length} renderer entries)`);
