// Collects deployments/<chainId>.json into src/lib/deployments.generated.ts so the static build can import them.
import fs from 'node:fs';
import path from 'node:path';

const dir = path.resolve('deployments');
const out = path.resolve('src/lib/deployments.generated.ts');
const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /^\d+\.json$/.test(f)) : [];
const entries = files.map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
const body = `// GENERATED by scripts/gen-deployments.mjs from deployments/*.json. Do not edit.\nimport type { Deployment } from './deployments';\nexport const DEPLOYMENTS: Readonly<Record<number, Deployment>> = ${JSON.stringify(Object.fromEntries(entries.map((e) => [e.chainId, e])), null, 2)};\n`;
fs.writeFileSync(out, body);
console.log(`deployments: ${entries.length ? entries.map((e) => `${e.chainId} (${e.chainName})`).join(', ') : 'none yet, the site will show the undeployed state'}`);
